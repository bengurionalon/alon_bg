CREATE TABLE IF NOT EXISTS reactions (chapter TEXT NOT NULL, pid TEXT NOT NULL, voter TEXT NOT NULL, emoji TEXT NOT NULL, at INTEGER NOT NULL, PRIMARY KEY (chapter, pid, voter));
CREATE INDEX IF NOT EXISTS reactions_chapter ON reactions (chapter);
CREATE TABLE IF NOT EXISTS reviews (id TEXT PRIMARY KEY, name TEXT NOT NULL, body TEXT NOT NULL, at INTEGER NOT NULL, hidden INTEGER NOT NULL DEFAULT 0);
CREATE INDEX IF NOT EXISTS reviews_at ON reviews (hidden, at DESC);
CREATE TABLE IF NOT EXISTS rate (k TEXT PRIMARY KEY, at INTEGER NOT NULL, n INTEGER NOT NULL);
